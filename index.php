<?php

$name = "Джамшут"; // змінна з ім'ям користувача
$age = 17; // змінна з віком
$is_student = true; // логічна змінна: студент чи ні

echo "Мене звати " . $name . ", мені " . $age . " років. "; // вивід базової інформації

if ($is_student) { // перевірка: чи студент
    echo "Я є студентом.<br>"; // якщо true
} else {
    echo "Я не є студентом.<br>"; // якщо false
}

$numbers = [1, 2, 3, 4, 5]; // масив чисел
$sum = 0; // змінна для суми

foreach ($numbers as $num) { // цикл перебору масиву
    $sum += $num; // додавання кожного елемента до суми
}

echo "Сума елементів масиву: " . $sum . "<br>"; // вивід суми

$user = [
    "name" => "Равшан", // ім'я користувача
    "email" => "tajikistan@gmail.com", // email
    "phone" => "+380123456789" // телефон
];

echo "<ul>"; 

foreach ($user as $key => $value) { // перебір асоціативного масиву
    echo "<li>" . $key . ": " . $value . "</li>"; // вивід ключів і значень
}

echo "</ul>"; // кінець списку

if ($age >= 18) { // перевірка віку
    echo "Ви повнолітній.<br>"; // якщо більше 18
} else {
    echo "Ви неповнолітній.<br>"; // якщо 18 або менше
}

$grade = 85; // змінна оцінки

if ($grade >= 90 && $grade <= 100) { // діапазон 90-100
    echo "Оцінка: Відмінно";
} elseif ($grade >= 70) { // діапазон 70-89
    echo "Оцінка: Добре";
} elseif ($grade >= 50) { // діапазон 50-69
    echo "Оцінка: Задовільно";
} else {
    echo "Оцінка: Незадовільно"; // менше 50
}

?>